// Sort keys descending by length so longer specific compound phrases match before single-word substrings
export const SORTED_ASIAN_KEYS = Object.keys(ASIAN_NAME_MAP).sort((a, b) => b.length - a.length);

/**
 * Strips category brackets like [支援者], [ZH], [JP], [KR], [CH] and numbers
 */
function cleanRawName(raw: string): string {
  return raw
    .replace(/\[(支援者|訓練家|トレーナー|서포트|트레이너|ZH|CH|JP|JA|KR|EN)\]/gi, '')
    .replace(/\s*-\s*\d+\/\d+.*$/i, '')
    .trim();
}

/**
 * Universal translator for Asian card names (Japanese, Korean, Traditional & Simplified Chinese)
 * Always guarantees an English card name for the user.
 */
export function translateAsianCardName(rawName: string): { englishName: string; isTranslated: boolean } {
  if (!rawName) return { englishName: '', isTranslated: false };

  const clean = cleanRawName(rawName);

  // 1. Direct exact dictionary match
  if (ASIAN_NAME_MAP[clean]) {
    return { englishName: ASIAN_NAME_MAP[clean], isTranslated: true };
  }

  // 2. Longest substring matching
  for (const key of SORTED_ASIAN_KEYS) {
    if (clean.includes(key)) {
      const translated = ASIAN_NAME_MAP[key];
      // If the clean name was just key + suffixes/prefixes, return the translated name
      return { englishName: translated, isTranslated: true };
    }
  }

  // 3. If card name contains non-Latin Asian scripts and still unmapped, clean up bracket noise
  const hasAsianScripts = /[\u3000-\u303f\u3040-\u309f\u30a0-\u30ff\uff00-\uff9f\u4e00-\u9faf\uac00-\ud7af]/.test(clean);
  if (!hasAsianScripts) {
    return { englishName: clean, isTranslated: false };
  }

  // Return cleaned name
  return { englishName: clean, isTranslated: false };
}
